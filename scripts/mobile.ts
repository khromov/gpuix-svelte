export function scaffold(config: MobileConfig, project_root = root) {
	const gen = join(project_root, '.gpuix/mobile');
	const mark = join(gen, '.gpuix-mobile');
	if (existsSync(gen) && !existsSync(mark)) error(`refusing to write ${gen}: it is not marked as gpuix-svelte generated`);
	mkdirSync(gen, { recursive: true });
	writeFileSync(mark, 'Generated by gpuix-svelte mobile; this directory is safe to replace.\n');

	write_file(join(gen, 'native/Cargo.toml'), rust_files());
	write_file(join(gen, 'native/src/lib.rs'), '#[cfg(target_os = "android")]\nmod android;\n#[cfg(target_os = "ios")]\nmod ios;\n');
	for (const name of ['android.rs', 'ios.rs']) write_file(join(gen, 'native/src', name), template(name));
	write_file(join(gen, 'native/.gpuix-mobile'), 'Generated by gpuix-svelte mobile; safe to replace.\n');
	android_files(config, project_root);
	ios_files(config, project_root);
}

function init(explicit_entry?: string) {
	safe_generated_dir();
	const config = read_mobile_config(explicit_entry, root);
	scaffold(config);
	console.log(`[mobile] created ${generated}; configure app settings in render()`);
}

function output(command: string, args: string[]): string {
	const result = spawnSync(command, args, { encoding: 'utf8' });
	if (result.status !== 0 || !result.stdout?.trim()) error(`${command} ${args.join(' ')} failed: ${result.error?.message ?? result.stderr}`);
	return result.stdout.trim();
}

function executable(path: string): boolean {
	try { accessSync(path, process.platform === 'win32' ? constants.F_OK : constants.X_OK); return true; } catch { return false; }
}

export function ios_build_tools(env: NodeJS.ProcessEnv = process.env, home = homedir()): { cmake: string; ninja: string; xcodegen: string } {
	const sdk = env.ANDROID_HOME ?? env.ANDROID_SDK_ROOT ?? join(home, 'Library/Android/sdk');
	let versions: string[] = [];
	try { versions = readdirSync(join(sdk, 'cmake')).sort((a, b) => b.localeCompare(a, undefined, { numeric: true })); } catch { /* Android Studio may not be installed. */ }
	const paths = (env.PATH ?? '').split(delimiter).map(path => path || '.');
	const sdk_bins = versions.map(version => join(sdk, 'cmake', version, 'bin'));
	const find = (name: string, fallback: string[]) => [...paths, ...fallback].map(path => resolve(path, name)).find(executable);
	const cmake = find('cmake', sdk_bins);
	const ninja = find('ninja', sdk_bins);
	const xcodegen = find('xcodegen', []);
	const missing = [!cmake && 'cmake', !ninja && 'ninja', !xcodegen && 'xcodegen'].filter(Boolean);
	if (missing.length) error(`missing iOS build tools: ${missing.join(', ')}. Install them with: brew install ${missing.join(' ')}`);
	return { cmake: cmake!, ninja: ninja!, xcodegen: xcodegen! };
}

export function find_gradle(env: NodeJS.ProcessEnv = process.env, project = root): string | undefined {
	const find = (command: string) => {
		if (command.includes('/') || command.includes('\\')) return executable(command) ? command : undefined;
		const names = process.platform === 'win32' ? [`${command}.bat`, `${command}.cmd`, `${command}.exe`, command] : [command];
		return (env.PATH ?? '').split(delimiter).flatMap(dir => names.map(name => join(dir || '.', name))).find(executable);
	};
	if (env.GRADLE) return find(env.GRADLE);
	const wrapper = join(project, process.platform === 'win32' ? 'gradlew.bat' : 'gradlew');
	if (executable(wrapper)) return wrapper;
	const installed = find('gradle');
	if (installed) return installed;
	const home = env.GRADLE_USER_HOME ?? join(homedir(), '.gradle');
	const distributions = join(home, 'wrapper/dists/gradle-9.4.1-bin');
	try {
		for (const dir of readdirSync(distributions).sort()) {
			const binary = join(distributions, dir, 'gradle-9.4.1/bin', process.platform === 'win32' ? 'gradle.bat' : 'gradle');
			if (executable(binary)) return binary;
		}
	} catch { /* The wrapper cache may not exist yet. */ }
	return undefined;
}

const WRAPPER_SHA256 = '55243ef57851f12b070ad14f7f5bb8302daceeebc5bce5ece5fa6edb23e1145c';
const DISTRIBUTION_SHA256 = '2ab2958f2a1e51120c326cad6f385153bb11ee93b3c216c5fccebfdfbb7ec6cb';

export async function gradle_wrapper(directory: string, download: (url: string) => Promise<Response> = fetch): Promise<string> {
	const jar = join(directory, 'gradle/wrapper/gradle-wrapper.jar');
	const valid = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex') === WRAPPER_SHA256;
	if (!existsSync(jar) || !valid(readFileSync(jar))) {
		console.log('[mobile] downloading the Gradle 9.4.1 wrapper');
		const response = await download('https://raw.githubusercontent.com/gradle/gradle/v9.4.1/gradle/wrapper/gradle-wrapper.jar');
		if (!response.ok) throw new Error(`[mobile] could not download the Gradle wrapper: HTTP ${response.status}`);
		const bytes = new Uint8Array(await response.arrayBuffer());
		if (!valid(bytes)) throw new Error('[mobile] Gradle wrapper checksum mismatch');
		write_file(jar, bytes);
	}
	write_file(join(directory, 'gradle/wrapper/gradle-wrapper.properties'), `distributionUrl=https\\://services.gradle.org/distributions/gradle-9.4.1-bin.zip\ndistributionSha256Sum=${DISTRIBUTION_SHA256}\n`);
	return jar;
}

async function build(platform: 'android' | 'ios', run_after: boolean, options: { simulator: boolean; device?: string; release: boolean; entry?: string }) {
	const config = read_mobile_config(options.entry, root);
	const entry = resolve(root, config.entry);
	if (!existsSync(entry)) error(`entry does not exist: ${entry}; set entry file or create app.ts with render()`);
	const ios_tools = platform === 'ios' ? ios_build_tools() : undefined;
	let gradle = platform === 'android' ? find_gradle() : undefined;
	let gradle_args: string[] = [];
	if (platform === 'android' && !gradle) {
		if (process.env.GRADLE) error(`GRADLE executable not found: ${process.env.GRADLE}`);
		gradle = process.env.JAVA_HOME ? join(process.env.JAVA_HOME, 'bin', process.platform === 'win32' ? 'java.exe' : 'java') : 'java';
		const java = spawnSync(gradle, ['-version'], { stdio: 'ignore' });
		if (java.error || java.status !== 0) error('Java not found; install JDK 17 or later and set JAVA_HOME or add java to PATH');
		const android = join(generated, 'android');
		safe_generated_dir();
		gradle_args = ['-classpath', await gradle_wrapper(android), 'org.gradle.wrapper.GradleWrapperMain'];
		run_command(gradle, [...gradle_args, '--version'], android);
	}
	run_command(process.execPath, [join(scripts, 'prepare-native-deps.mjs')]);
	scaffold(config);
	const files = await build_txiki_bundle(entry, { platform, production: true });
	const assets = join(generated, platform === 'android' ? 'android/app/src/main/assets' : 'ios/assets');
	if (existsSync(assets)) for (const name of readdirSync(assets)) if (name.startsWith('gpuix-asset-') || name === 'gpuix-resources') rmSync(join(assets, name), { recursive: true, force: true });
	for (const [name, bytes] of files) write_file(join(assets, name), bytes);
	for (const name of config.assets ?? []) copy_asset(name, assets);
	const manifest = join(generated, 'native/Cargo.toml');
	const cargo_target = process.env.CARGO_TARGET_DIR ? resolve(process.env.CARGO_TARGET_DIR) : join(generated, 'native/target');
	const work = join(generated, 'txiki');
	const source = prepare_txiki(platform, work);
	if (platform === 'android') {
		const sdk = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT ?? join(homedir(), process.platform === 'darwin' ? 'Library/Android/sdk' : 'Android/Sdk');
		const ndk = process.env.ANDROID_NDK_HOME ?? join(sdk, 'ndk', config.android.ndkVersion);
		const host = process.platform === 'darwin' ? 'darwin-x86_64' : process.platform === 'linux' ? 'linux-x86_64' : 'windows-x86_64';
		const llvm = join(ndk, 'toolchains/llvm/prebuilt', host);
		const env = { ANDROID_HOME: sdk, ANDROID_NDK_HOME: ndk, CLANG_PATH: process.env.CLANG_PATH ?? join(llvm, 'bin/clang'), BINDGEN_EXTRA_CLANG_ARGS: `${process.env.BINDGEN_EXTRA_CLANG_ARGS ?? ''} --sysroot=${join(llvm, 'sysroot')}`, CARGO_TARGET_DIR: cargo_target, GPUIX_TXIKI_SOURCE: source };
		for (const abi of config.android.abis) run_command('cargo', ['ndk', '-t', abi, '-P', String(config.android.minSdk), '-o', join(generated, 'android/app/src/main/jniLibs'), 'build', '--manifest-path', manifest, '--lib', '--release'], join(generated, 'native'), env);
		run_command(gradle!, [...gradle_args, ...(options.release ? ['assembleRelease', 'bundleRelease'] : ['assembleDebug'])], join(generated, 'android'), env);
		if (run_after) {
			if (options.release && !process.env.GPUIX_ANDROID_KEYSTORE) error('running a release APK requires GPUIX_ANDROID_KEYSTORE and signing credentials');
			const devices = output('adb', ['devices']).split('\n').filter(line => /\tdevice$/.test(line)).map(line => line.split('\t')[0]!);
			const selected = options.device ?? devices[0];
			if (!selected || !devices.includes(selected)) error('no authorized Android device/emulator matches; connect one or pass --device <serial>');
			run_command('adb', ['-s', selected!, 'install', '-r', join(generated, options.release ? 'android/app/build/outputs/apk/release/app-release.apk' : 'android/app/build/outputs/apk/debug/app-debug.apk')]);
			run_command('adb', ['-s', selected!, 'shell', 'am', 'start', '-n', `${config.appId}/dev.gpuix.mobile.MainActivity`]);
		}
	} else {
		const arch = ios_architecture(options.simulator);
		const sdk = output('xcrun', ['--sdk', options.simulator ? 'iphonesimulator' : 'iphoneos', '--show-sdk-path']);
		const library = build_txiki_ios(source, work, options.simulator, arch.xcode, config.ios.deploymentTarget, ios_tools!);
		run_command('cargo', ['build', '--manifest-path', manifest, '--lib', '--release', '--target', arch.rust], root, { ...ios_cargo_env(config, output('xcrun', ['--find', 'clang']), `-isysroot ${sdk}`), CARGO_TARGET_DIR: cargo_target });
		run_command(ios_tools!.xcodegen, ['generate', '--spec', 'project.yml'], join(generated, 'ios'));
		const args = ['-project', join(generated, 'ios', `${config.name}.xcodeproj`), '-scheme', config.name, '-configuration', options.release ? 'Release' : 'Debug', '-derivedDataPath', join(generated, 'ios/DerivedData'), '-destination', options.device ? `id=${options.device}` : options.simulator ? 'generic/platform=iOS Simulator' : 'generic/platform=iOS', `ARCHS=${arch.xcode}`, 'ONLY_ACTIVE_ARCH=YES', `TXIKI_SOURCE=${source}`, `TXIKI_LIB=${library}`, `GPUIX_RUST_LIB=${join(cargo_target, arch.rust, 'release/libgpuix_app.a')}`];
		if (options.simulator) args.push('CODE_SIGNING_ALLOWED=NO');
		run_command('xcodebuild', [...args, 'build']);
		if (run_after) {
			const device = options.device;
			if (!device) error('iOS run needs --device <UDID>; use --simulator for a simulator destination');
			const app = join(generated, `ios/DerivedData/Build/Products/${options.release ? 'Release' : 'Debug'}-${options.simulator ? 'iphonesimulator' : 'iphoneos'}`, `${config.name}.app`);
			if (options.simulator) {
				const booted = JSON.parse(output('xcrun', ['simctl', 'list', 'devices', 'booted', '--json'])).devices as Record<string, { udid: string }[]>;
				if (!Object.values(booted).flat().some(item => item.udid === device)) run_command('xcrun', ['simctl', 'boot', device!]);
				run_command('xcrun', ['simctl', 'bootstatus', device!, '-b']);
				run_command('xcrun', ['simctl', 'install', device!, app]);
				run_command('xcrun', ['simctl', 'launch', device!, config.appId]);
			} else {
				run_command('xcrun', ['devicectl', 'device', 'install', 'app', '--device', device!, app]);
				run_command('xcrun', ['devicectl', 'device', 'process', 'launch', '--device', device!, config.appId]);
			}
		}
	}
	console.log(`[mobile] txiki ${platform} ${run_after ? 'build and launch' : 'build'} complete`);
}

export function watchable(path: string) {
	return !path.split(/[\\/]/).some(part => part === '.gpuix' || part === '.git' || part === 'node_modules' || part === 'dist');
}

export async function run(argv = process.argv.slice(2)) {
	const [action, platform, ...rest] = argv;
	if (action === 'init') {
		const entry = platform && !platform.startsWith('--') ? platform : rest.find(arg => !arg.startsWith('--'));
		return init(entry);
	}
	if (action !== 'build' && action !== 'run') error('expected init, build or run');
	if (platform !== 'android' && platform !== 'ios') error('expected android or ios');
	let simulator = false; let release = false; let watching = false; let device: string | undefined; let entry: string | undefined;
	for (let index = 0; index < rest.length; index++) {
		if (rest[index] === '--simulator') simulator = true;
		else if (rest[index] === '--release') release = true;
		else if (rest[index] === '--watch') watching = true;
		else if (rest[index] === '--device' && rest[index + 1]) device = rest[++index];
		else if (!rest[index]!.startsWith('--') && !entry) entry = rest[index];
		else error(`unknown option ${rest[index]}`);
	}
	if (watching && action !== 'run') error('--watch requires mobile run');
	if (watching && release) error('--watch cannot be combined with --release');
	const options = { simulator, device, release, entry };
	await build(platform as 'android' | 'ios', action === 'run', options);
	if (!watching) return;
	let timer: ReturnType<typeof setTimeout> | undefined;
	let building = false;
	let pending = false;
	const rebuild = async () => {
		if (building) { pending = true; return; }
		building = true;
		try {
			console.log('[mobile] rebuilding after a change');
			await build(platform as 'android' | 'ios', true, options);
		} catch (error) { console.error(error); }
		finally {
			building = false;
			if (pending) { pending = false; timer = setTimeout(rebuild, 300); }
		}
	};
	const watcher = watch(root, { recursive: true }, (_event, name) => {
		if (!name || !watchable(name.toString())) return;
		clearTimeout(timer);
		timer = setTimeout(rebuild, 300);
	});
	console.log('[mobile] watching the project; changes rebuild and relaunch the app');
	await new Promise<void>((resolve, reject) => {
		const stop = () => { clearTimeout(timer); watcher.close(); resolve(); };
		watcher.on('error', reject);
		process.once('SIGINT', stop);
		process.once('SIGTERM', stop);
	});
}

if (import.meta.main) await run();
