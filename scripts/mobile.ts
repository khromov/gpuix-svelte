import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { build_txiki_bundle } from '../src/txiki-bundle.ts';
import { DEFAULT_MOBILE_CONFIG, read_mobile_config, type MobileConfig } from './mobile-config.ts';
import { prepare_txiki, build_txiki_ios, txiki_command } from './txiki-source.ts';

const root = process.cwd();
const package_root = dirname(fileURLToPath(import.meta.resolve('gpuix-svelte/package.json')));
const scripts = join(package_root, 'scripts');
const gpuix = join(package_root, '.generated/gpuix');
const generated = join(root, '.gpuix/mobile');
const marker = join(generated, '.gpuix-mobile');
const usage = 'usage: gpuix-svelte mobile init | build|run android|ios [--simulator] [--device <id>]';
const error = (message: string): never => { throw new Error(`[mobile] ${message}\n${usage}`); };
const esc = (value: string) => JSON.stringify(value);
const template = (name: string) => readFileSync(join(package_root, 'native/mobile', name), 'utf8');
const run_command = (command: string, args: string[], cwd = root, env: NodeJS.ProcessEnv = {}) => txiki_command(command, args, cwd, env);

function write_file(path: string, content: string | Uint8Array) {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, content);
}

function safe_generated_dir() {
	if (existsSync(generated) && !existsSync(marker)) error(`refusing to write ${generated}: it is not marked as gpuix-svelte generated`);
	mkdirSync(generated, { recursive: true });
	writeFileSync(marker, 'Generated by gpuix-svelte mobile; this directory is safe to replace.\n');
}

