export function ios_architecture(simulator: boolean, host_arch: string = process.arch) {
	const arm = !simulator || host_arch === 'arm64';
	return { rust: arm ? (simulator ? 'aarch64-apple-ios-sim' : 'aarch64-apple-ios') : 'x86_64-apple-ios', xcode: arm ? 'arm64' : 'x86_64' };
}

export function ios_cargo_env(config: MobileConfig, clang: string, bindgen_args: string): NodeJS.ProcessEnv {
	return { CLANG_PATH: process.env.CLANG_PATH ?? clang, BINDGEN_EXTRA_CLANG_ARGS: bindgen_args, IPHONEOS_DEPLOYMENT_TARGET: config.ios.deploymentTarget };
}

