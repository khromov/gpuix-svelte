import { dismiss_layer, on_window_back } from 'gpuix-svelte';
import { handle_back } from '../src/back.ts';
import { start_router, stop_router, navigate, router } from 'gpuix-svelte-ui/router';
import { check, finish } from 'gpuix-svelte/test';

start_router({ initial: '/' });
await navigate('/second');
const seen: string[] = [];
const close = dismiss_layer({ onEscape: () => seen.push('outer') });
const inner = dismiss_layer({ onEscape: () => seen.push('inner') });
check('Back reaches only the top overlay before the router', [handle_back(), seen, router.path], [true, ['inner'], '/second']);
inner();
check('the next Back reaches the outer layer', [handle_back(), seen], [true, ['inner', 'outer']]);
close();
const locked = dismiss_layer({ onEscape() {} });
check('a nondismissable layer still consumes Back', [handle_back(), router.path], [true, '/second']);
locked();
check('without a layer Back navigates to the previous screen', [handle_back(), router.path], [true, '/']);
check('at the first screen Back belongs to the OS', handle_back(), false);
stop_router();
check('stopping the router removes its Back handler', handle_back(), false);
let hits = 0;
const handler = () => { hits++; return true; };
const off = on_window_back(handler);
off();
const later = on_window_back(handler);
off();
check('a spent unsubscribe cannot remove a later identical handler', [handle_back(), hits], [true, 1]);
later();
check('the later unsubscribe leaves no handler', handle_back(), false);
finish('mobile-back', 8);
